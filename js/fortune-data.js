// 날짜 시드 기반 결정론적 RNG (같은 날 항상 같은 결과)
function getDailyFortune() {
  const d = new Date();
  const seed = d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();

  function seededRng(s, offset) {
    const x = Math.sin(s * 9301 + offset * 49297 + 233) * 10000;
    return x - Math.floor(x);
  }

  const pick = (arr, offset) => arr[Math.floor(seededRng(seed, offset) * arr.length)];

  return {
    work:     pick(FORTUNE_DATA.work, 0),
    money:    pick(FORTUNE_DATA.money, 1),
    relation: pick(FORTUNE_DATA.relation, 2),
    lucky: {
      number: Math.floor(seededRng(seed, 3) * 9) + 1,
      color:  ['빨강', '주황', '노랑', '초록', '파랑', '남색', '보라', '흰색', '검정'][Math.floor(seededRng(seed, 4) * 9)],
      word:   ['성실', '도전', '소통', '신뢰', '열정', '인내', '지혜', '협력', '감사', '긍정'][Math.floor(seededRng(seed, 5) * 10)],
    },
    score: {
      work:     Math.floor(seededRng(seed, 6) * 5) + 1,
      money:    Math.floor(seededRng(seed, 7) * 5) + 1,
      relation: Math.floor(seededRng(seed, 8) * 5) + 1,
    },
    date: `${d.getFullYear()}년 ${d.getMonth() + 1}월 ${d.getDate()}일`,
  };
}
